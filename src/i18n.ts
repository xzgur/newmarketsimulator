const DICTS: Record<Lang, Dict> = { en: EN, tr: TR, es: ES, de: DE };

export function t(key: string, vars?: Record<string, string | number>): string {
  let s = DICTS[current][key] ?? EN[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** One random entry of a "|"-separated line list. */
export function pick(key: string): string {
  const list = t(key).split('|');
  return list[Math.floor(Math.random() * list.length)];
}

/** Every key exists in every language (used by tests). */
export function missingKeys(): string[] {
  const out: string[] = [];
  for (const lang of Object.keys(DICTS) as Lang[]) {
    for (const k of Object.keys(EN)) if (!(k in DICTS[lang])) out.push(`${lang}:${k}`);
  }
  return out;
}

export function speechLang(): string {
  return { en: 'en-US', tr: 'tr-TR', es: 'es-ES', de: 'de-DE' }[current];
}
